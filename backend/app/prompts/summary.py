"""ASR/OCR 요약용 프롬프트 - 3회 분리 호출.

각 호출의 출력 형식을 단순화하여 파싱 실패를 방지합니다.
- 1단계: 키워드 + 목차 (쉼표 구분 리스트)
- 2단계: 핵심요약 + 상세요약 (마크다운)
- 3단계: 제목 생성
"""

